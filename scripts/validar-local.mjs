import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
const base = 'http://127.0.0.1:5173';
let cookie = '';
async function call(path, method = 'GET', body, expected = 200, authenticated = true) {
  const response = await fetch(`${base}/api/${path}`, { method, headers: { ...(authenticated && cookie ? { cookie } : {}), ...(body ? { 'content-type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined });
  const data = await response.json();
  assert.equal(response.status, expected, `${method} ${path}: ${data.error?.message || response.status}`);
  return { response, data };
}
const profile = (await call('perfil')).data;
assert.equal(profile.local, true, 'Este script só pode testar a base local isolada.');
for (const path of ['/', '/painel/', '/assets/js/painel/view-host.js', '/assets/js/painel/operacao.js']) assert.equal((await fetch(base + path)).status, 200);
const login = await call('login', 'POST', { senha: process.env.PAINEL_SENHA });
cookie = login.response.headers.get('set-cookie').split(';')[0];
for (const route of ['painel/inicio', 'painel/agenda', 'painel/retornos', 'painel/clientes', 'painel/servicos', 'painel/ajustes', 'painel/operacao']) await call(route);
const service = profile.services.find(s => s.name.includes('teste')) || profile.services[0];
assert.equal(service.durationMin, undefined);
const days = (await call(`horarios?servico=${service.id}`)).data;
const day = days.find(d => d.slots.length);
assert.ok(day);
const payload = { name: 'Cliente HTTP de validação', phone: '81900000002', vehicle: 'Carro HTTP de teste', plate: 'JKL1M23', serviceId: service.id, date: day.date, start: day.slots[0].time, idempotencyKey: randomUUID() };
const booking = (await call('agendamentos', 'POST', payload, 200, false)).data.appointment;
const duplicate = (await call('agendamentos', 'POST', payload, 200, false)).data.appointment;
assert.equal(booking.id, duplicate.id);
assert.equal((await call(`reserva/${booking.manageToken}`, 'GET', undefined, 200, false)).data.appointment.id, booking.id);
const slots = (await call(`painel/horarios?servico=${service.id}&data=${day.date}&ignorar=${booking.id}`)).data.slots;
const start = slots.at(-1).time;
await call(`painel/agendamentos/${booking.id}`, 'PUT', { dados: { ...payload, start }, encaixe: false });
assert.equal((await call(`painel/agendamentos/${booking.id}`)).data.start, start);
await call(`painel/agendamentos/${booking.id}`, 'PATCH', { status: 'cancelado' });
await call(`painel/servicos/${service.id}`, 'DELETE', undefined, 409);
const disposable = (await call('painel/servicos', 'PUT', { name: 'Serviço descartável HTTP', description: 'Item um\nItem dois', priceCents: 4050 })).data;
await call(`painel/servicos/${disposable.id}`, 'DELETE');
const data = (await call('painel/exportar')).data;
assert.ok(!data.appointments.some(a => a.manageToken || a.requestFingerprint));
await call('logout', 'POST', {});
await call('painel/ajustes', 'GET', undefined, 401);
console.log('HTTP local aprovado: páginas, módulos, login, todas as telas/API, reserva idempotente, gestão por token, remarcação, cancelamento, exclusão protegida, exportação e logout.');
